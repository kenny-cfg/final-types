interface Product {
  id: number;
  name: string;
  price: number;
  inStock: boolean;
}

/*
First, a type called ProductCard that only includes the name and price fields for use in a product listing.
*/

type ProductCard = Pick<Product, 'name' | 'price'>;

/*
Second, a type called NewProduct that includes everything except id, since that will be generated by the database when a new product is created.
*/

type NewProduct = Omit<Product, 'id'>;

const productCard: ProductCard = {
  name: 'Shoes',
  price: 54,
}

const newProduct: NewProduct = {
  name: 'Gloves',
  price: 12,
  inStock: false,
}